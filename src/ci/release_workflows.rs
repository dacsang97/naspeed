//! `ns-build.yml` (snapshot builds on main that warm the release cache) and
//! `ns-release.yml` (tagged releases that read it), the counterparts of a
//! snapshot build / tagged release workflow pair.

use super::workflow_templates::{
    CacheKind, Job, RELEASE_EXPORT_MAX_GB, WORKFLOW_ENV, fill, save_steps, setup_steps,
};
use super::{ImageTarget, WorkflowSpec};

/// Why both release workflows use macOS, repeated in each header.
const RUNNER_NOTE: &str = r#"# Runner: macos-latest. Apple targets (universal2-apple-darwin) only link
# natively on macOS, while Linux musl/gnu targets link through zig and
# x86_64-pc-windows-msvc through xwin + lld, so one macOS runner covers the
# whole matrix. ns-build and ns-release must share the runner: the release
# cache key includes the runner OS and arch."#;

const BUILD_TEMPLATE: &str = r#"# Generated by `ns ci init` for @PROJECT@. Edit freely; `ns ci init --force`
# regenerates it.
#
# Snapshot build only: compile-checks every release target and every build
# variant (@BUILDS@) on main and warms the release cache,
# so tagged releases start hot. `ns release --snapshot` never publishes and
# does not push images, so no registry login or Docker daemon is needed here.
#
@RUNNER_NOTE@
#
# Security model: the token is read-only (`contents: read`), and the cache is
# written only by pushes to main (this workflow's only trigger; the steps are
# guarded anyway). The export is capped at @MAX_GB@ GB (see ns-ci.yml for the
# budget).
name: @PROJECT@ build

on:
  push:
    branches: [main]

permissions:
  contents: read

@ENV@
jobs:
  snapshot:
    runs-on: macos-latest
    steps:
@SETUP@@BEFORE@      - name: Snapshot release build
        run: ns release --snapshot
@SAVE@"#;

const RELEASE_TEMPLATE: &str = r#"# Generated by `ns ci init` for @PROJECT@. Edit freely; `ns ci init --force`
# regenerates it.
#
# Tagged release of @BUILDS@. `ns release --publish` runs
# the `before` hooks, builds every target, archives, writes checksums and
# SBOMs, signs the checksum file keyless with cosign and creates the GitHub
# Release. Draft, prerelease and changelog settings come from ns.toml.
#
@RUNNER_NOTE@
#
# Security model
# - The release cache saved by ns-build on main is restored, never saved: tag
#   runs only read it.
# - `contents: write` creates the GitHub Release, `id-token: write` gives
#   cosign its keyless OIDC identity, `packages: write` lets `ns image` push to
#   ghcr.io with GITHUB_TOKEN.
@IMAGE_NOTE@name: @PROJECT@ release

on:
  push:
    tags: ['v*']

permissions:
  contents: write
  packages: write
  id-token: write

@ENV@
jobs:
  release:
    runs-on: macos-latest
    steps:
@SETUP@@BEFORE@      - uses: @COSIGN_INSTALLER@
      - name: Release
        env:
          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        run: ns release --publish
@IMAGE@"#;

const IMAGE_SAME_JOB: &str = r#"      # ns image pushes over the registry HTTP API (no Docker daemon) and
      # authenticates to ghcr.io with GITHUB_TOKEN.
      - name: Push image
        env:
          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}
        run: ns image --push
"#;

const IMAGE_SEPARATE_JOB: &str = r#"      - name: Upload dist for the image job
        uses: @UPLOAD_ARTIFACT@
        with:
          name: dist
          path: dist
          retention-days: 1
          if-no-files-found: error

  image:
    needs: release
    # docker/login-action needs the docker CLI, which macOS runners lack, so
    # the push runs on Linux from the release job's dist dir.
    runs-on: ubuntu-latest
    permissions:
      contents: read
    steps:
@IMAGE_SETUP@      - uses: @DOWNLOAD_ARTIFACT@
        with:
          name: dist
          path: dist
      # PLACEHOLDER secrets: create REGISTRY_USERNAME / REGISTRY_PASSWORD (a
      # push token) for @REGISTRY@ in the repository settings. The login writes
      # ~/.docker/config.json, which `ns image` reads.
      - uses: @DOCKER_LOGIN@
        with:
          registry: @REGISTRY@
          username: ${{ secrets.REGISTRY_USERNAME }}
          password: ${{ secrets.REGISTRY_PASSWORD }}
      - name: Push image
        run: ns image --push
"#;

/// Comment before the release step when ns.toml has `before` hooks: their
/// tools (bun, node, …) are not installed by the generated steps.
fn before_note(spec: &WorkflowSpec) -> String {
    match spec.before_hooks {
        0 => String::new(),
        n => format!(
            "      # ns release runs {n} `before` hook(s) from ns.toml first: add setup\n      # steps above for the tools they need.\n"
        ),
    }
}

fn builds_summary(spec: &WorkflowSpec) -> String {
    match spec.builds.len() {
        0 => "no build variants".to_owned(),
        1 => format!("1 build variant: {}", spec.builds[0]),
        n => format!("{n} build variants: {}", spec.builds.join(", ")),
    }
}

fn finish(text: String, spec: &WorkflowSpec) -> String {
    let text = text
        .replace("@RUNNER_NOTE@", RUNNER_NOTE)
        .replace("@ENV@", WORKFLOW_ENV)
        .replace("@BEFORE@", &before_note(spec))
        .replace("@BUILDS@", &builds_summary(spec))
        .replace("@PROJECT@", &spec.project);
    fill(&text, &spec.ns_version)
}

pub fn render_build(spec: &WorkflowSpec) -> String {
    let text = BUILD_TEMPLATE
        .replace("@SETUP@", &setup_steps(Job::Snapshot, spec.toolchain))
        .replace("@SAVE@", &save_steps(CacheKind::Release))
        .replace("@MAX_GB@", &RELEASE_EXPORT_MAX_GB.to_string());
    finish(text, spec)
}

pub fn render_release(spec: &WorkflowSpec) -> String {
    let (image, note) = match &spec.image {
        None => (String::new(), String::new()),
        Some(ImageTarget {
            registry,
            ghcr: true,
        }) => (
            IMAGE_SAME_JOB.to_owned(),
            format!("# - The image goes to {registry} from the release job.\n"),
        ),
        Some(ImageTarget {
            registry,
            ghcr: false,
        }) => (
            IMAGE_SEPARATE_JOB
                .replace("@IMAGE_SETUP@", &setup_steps(Job::Image, spec.toolchain))
                .replace("@REGISTRY@", registry),
            format!(
                "# - The image goes to {registry} from a separate Linux job (read-only token)\n#   that logs in with placeholder secrets; see the `image` job.\n"
            ),
        ),
    };
    let text = RELEASE_TEMPLATE
        .replace("@SETUP@", &setup_steps(Job::Release, spec.toolchain))
        .replace("@IMAGE_NOTE@", &note)
        .replace("@IMAGE@", &image);
    finish(text, spec)
}

#[cfg(test)]
mod tests {
    use super::super::workflow_templates::{CACHE_SAVE, SAVE_GUARD, unreplaced_marker};
    use super::*;
    use crate::ci::tests::sample_spec;

    fn ghcr() -> Option<ImageTarget> {
        Some(ImageTarget {
            registry: "ghcr.io".into(),
            ghcr: true,
        })
    }

    #[test]
    fn build_snapshots_on_main_and_saves_the_release_cache() {
        let text = render_build(&sample_spec(None));
        assert!(unreplaced_marker(&text).is_none(), "{text}");
        assert!(text.contains("name: demo build\n"));
        assert!(text.contains("on:\n  push:\n    branches: [main]\n\npermissions:"));
        assert!(!text.contains("pull_request"));
        assert!(text.contains("2 build variants: api, api-noui"));
        assert!(text.contains("ns release --snapshot"));
        assert!(text.contains("runs-on: macos-latest"));
        assert!(text.contains("ns cache export ~/.naspeed-ci --max-gb 4"));
        assert_eq!(text.matches(CACHE_SAVE).count(), 1);
        assert_eq!(text.matches(&format!("if: {SAVE_GUARD}")).count(), 2);
        assert!(text.contains("2 `before` hook(s)"));
        assert!(!text.contains("docker/login-action"));
        assert!(!text.contains(": write"), "read-only token");
    }

    #[test]
    fn release_restores_never_saves_and_pushes_ghcr_in_job() {
        let text = render_release(&sample_spec(ghcr()));
        assert!(unreplaced_marker(&text).is_none(), "{text}");
        assert!(text.contains("tags: ['v*']"));
        assert!(
            text.contains(
                "permissions:\n  contents: write\n  packages: write\n  id-token: write\n"
            )
        );
        assert!(text.contains("cache/restore"));
        assert!(!text.contains(CACHE_SAVE));
        assert!(!text.contains("cache export"));
        assert!(text.contains("sigstore/cosign-installer"));
        assert!(text.contains("run: ns release --publish\n"));
        assert!(text.contains("ns image --push"));
        assert!(!text.contains("docker/login-action"));
        assert!(!text.contains("\n  image:\n"));
    }

    #[test]
    fn other_registries_push_from_a_linux_job_with_login() {
        let spec = sample_spec(Some(ImageTarget {
            registry: "registry.example.com:5000".into(),
            ghcr: false,
        }));
        let text = render_release(&spec);
        assert!(unreplaced_marker(&text).is_none(), "{text}");
        let (release, image) = text.split_once("\n  image:\n").expect("image job");
        assert!(release.contains("actions/upload-artifact"));
        assert!(!release.contains("run: ns image"));
        assert!(image.contains("runs-on: ubuntu-latest"));
        assert!(image.contains("needs: release"));
        assert!(image.contains("permissions:\n      contents: read\n"));
        assert!(image.contains("registry: registry.example.com:5000"));
        assert!(image.contains("secrets.REGISTRY_PASSWORD"));
        assert!(image.contains("ns image --push"));
        assert!(!image.contains("cache/restore"));
    }

    #[test]
    fn no_image_steps_without_an_image() {
        let text = render_release(&sample_spec(None));
        assert!(!text.contains("run: ns image"));
        assert!(!text.contains("artifact"));
    }
}
