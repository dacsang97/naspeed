//! `ns-ci.yml`: lint and tests on pull requests and pushes to main, with the
//! naspeed store restored from (and, on main only, saved to) actions cache.

use super::WorkflowSpec;
use super::workflow_templates::{CacheKind, Job, WORKFLOW_ENV, fill, save_steps, setup_steps};

const TEMPLATE: &str = r#"# Generated by `ns ci init` for @PROJECT@. Edit freely; `ns ci init --force`
# regenerates it.
#
# rustfmt and clippy with -D warnings for lint, and
# `ns test --locked` (cargo test plus naspeed's test-result cache: a test
# binary identical to one that already passed on main replays its output)
# for the tests. Lint runs in the Linux leg of the matrix before the tests,
# so one cache entry per OS holds the clippy and test artifacts and results.
#
# Security model
# - The naspeed store cache is restored on every run but saved only by pushes
#   to main. Pull requests run code from their author (forks included): if a
#   PR could save the cache, it could plant compiled artifacts that later main
#   and release builds restore and link into shipped binaries. GitHub scopes a
#   PR's caches to its merge ref, and main never reads them; not saving at all
#   also keeps the repository's cache budget for main.
# - The token is read-only (`contents: read`); checkout does not keep it.
# - naspeed itself is downloaded at a pinned version and checked against the
#   release's SHA256SUMS before it runs.
# - Each OS exports at most @MAX_GB@ GB: with ns-build's release cache, one push
#   to main stays within GitHub's default 10 GB cache budget per repository.
name: @PROJECT@ ci

on:
  push:
    branches: [main]
  pull_request:

permissions:
  contents: read

@ENV@
jobs:
  test:
    name: test (${{ matrix.os }})
    runs-on: ${{ matrix.os }}
    strategy:
      fail-fast: false
      matrix:
        os: [ubuntu-latest, macos-latest]
    steps:
@SETUP@      - name: Check formatting
        if: runner.os == 'Linux'
        run: cargo fmt --all --check
      - name: Clippy
        if: runner.os == 'Linux'
        run: cargo clippy --locked --all-targets -- -D warnings
      - name: Test
        run: ns test --locked
@SAVE@"#;

pub fn render(spec: &WorkflowSpec) -> String {
    let text = TEMPLATE
        .replace("@ENV@", WORKFLOW_ENV)
        .replace("@SETUP@", &setup_steps(Job::Test, spec.toolchain))
        .replace("@SAVE@", &save_steps(CacheKind::Test))
        .replace(
            "@MAX_GB@",
            &super::workflow_templates::TEST_EXPORT_MAX_GB.to_string(),
        )
        .replace("@PROJECT@", &spec.project);
    fill(&text, &spec.ns_version)
}

#[cfg(test)]
mod tests {
    use super::super::workflow_templates::{CACHE_SAVE, SAVE_GUARD, unreplaced_marker};
    use super::*;
    use crate::ci::tests::sample_spec;

    #[test]
    fn renders_lint_tests_and_a_guarded_save() {
        let text = render(&sample_spec(None));
        assert!(unreplaced_marker(&text).is_none(), "{text}");
        assert!(text.contains("name: demo ci\n"));
        assert!(text.contains("\n  pull_request:\n"));
        assert!(!text.contains("tags:"));
        assert!(text.contains("\npermissions:\n  contents: read\n\nenv:"));
        assert!(text.contains("cargo clippy --locked --all-targets -- -D warnings"));
        assert!(text.contains("cargo fmt --all --check"));
        assert!(text.contains("ns test --locked"));
        assert!(text.contains("os: [ubuntu-latest, macos-latest]"));
        assert_eq!(text.matches(CACHE_SAVE).count(), 1);
        assert_eq!(text.matches(&format!("if: {SAVE_GUARD}")).count(), 2);
        assert!(!text.contains(": write"), "no write permission anywhere");
    }
}
