//! `naspeed __link <triple> <tool> args…`: the stable entry point that
//! cargo's `linker` / `CC_<triple>` shims call. It (re)generates the
//! `zig cc` wrapper for the triple, then runs it. Those wrappers call back
//! into `naspeed zig cc -- …`, which handles argument filtering, the glibc
//! suffix and target-specific fixes.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, Result, bail};

use crate::cli::LinkArgs;
use crate::setup::installed_binary;

/// The executable zig wrappers should call back: the installed naspeed,
/// so wrappers never point into a target/ dir that may be rebuilt.
fn callback_exe() -> PathBuf {
    let installed = installed_binary();
    if installed.exists() {
        installed
    } else {
        std::env::current_exe().unwrap_or(installed)
    }
}

pub fn zig_wrapper(triple: &str) -> Result<cargo_zigbuild::zig::ZigWrapper> {
    // The generated wrappers run `exec <this exe> zig cc …`; this variable
    // is the documented override for that path.
    // SAFETY: single-threaded at this point (CLI startup, before any spawn).
    unsafe { std::env::set_var("CARGO_BIN_EXE_cargo-zigbuild", callback_exe()) };
    let config = cargo_config2::Config::load().context("load cargo config")?;
    cargo_zigbuild::zig::prepare_zig_linker(triple, &config)
        .with_context(|| format!("prepare zig wrapper for {triple}"))
}

pub fn tool_path(wrapper: &cargo_zigbuild::zig::ZigWrapper, tool: &str) -> Result<PathBuf> {
    Ok(match tool {
        "cc" | "ld" => wrapper.cc.clone(),
        "c++" => wrapper.cxx.clone(),
        "ar" => wrapper.ar.clone(),
        "ranlib" => wrapper.ranlib.clone(),
        "lib" => wrapper.lib.clone(),
        other => bail!("unknown shim tool {other}"),
    })
}

pub fn run(args: LinkArgs) -> Result<u8> {
    let wrapper = zig_wrapper(&args.triple)?;
    let tool = tool_path(&wrapper, &args.tool)?;
    let status = Command::new(&tool)
        .args(&args.args)
        .status()
        .with_context(|| format!("run {}", tool.display()))?;
    Ok(crate::wrapper::exit_code(status).clamp(0, 255) as u8)
}

/// Dispatch for the zig shims' `ar` / `lib` / `*dlltool` symlinks, which
/// point at this binary and are recognised by their file name.
pub fn zig_tool_for_argv0(argv0: &Path, rest: &[String]) -> Option<cargo_zigbuild::Zig> {
    let name = argv0.file_stem()?.to_str()?;
    let args = rest.to_vec();
    match name {
        "ar" => Some(cargo_zigbuild::Zig::Ar { args }),
        "lib" => Some(cargo_zigbuild::Zig::Lib { args }),
        n if n.ends_with("dlltool") => Some(cargo_zigbuild::Zig::Dlltool { args }),
        _ => None,
    }
}

/// Shell script installed for cargo: `exec naspeed __link <triple> <tool> "$@"`.
pub fn shim_script(bin: &Path, triple: &str, tool: &str) -> String {
    format!(
        "#!/bin/sh\n# generated by naspeed setup --cross\nexec '{}' __link '{triple}' '{tool}' \"$@\"\n",
        bin.display()
    )
}
