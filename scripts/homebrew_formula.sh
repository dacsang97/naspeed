#!/usr/bin/env bash
# Prints the Homebrew formula for one release to stdout.
#
#   scripts/homebrew_formula.sh v0.1.0 checksums/ > naspeed.rb
#
# checksums/ holds the `naspeed-<tag>-<target>.tar.gz.sha256` files written by
# the release-binaries workflow (`shasum -a 256` output: "<hash>  <file>").
set -euo pipefail

tag=${1:?usage: homebrew_formula.sh <tag> <sha256-dir>}
dir=${2:?usage: homebrew_formula.sh <tag> <sha256-dir>}
version=${tag#v}
repo=${GITHUB_REPOSITORY:-dacsang97/naspeed}
targets=(aarch64-apple-darwin x86_64-apple-darwin aarch64-unknown-linux-musl x86_64-unknown-linux-musl)

asset() { echo "naspeed-$tag-$1.tar.gz"; }

# Check every checksum up front: an `exit` inside the heredoc's command
# substitutions below would not stop the script.
for target in "${targets[@]}"; do
  file="$dir/$(asset "$target").sha256"
  [[ -s $file ]] || { echo "missing $file" >&2; exit 1; }
done

block() {
  cat <<EOF
      url "https://github.com/$repo/releases/download/$tag/$(asset "$1")"
      sha256 "$(cut -d' ' -f1 "$dir/$(asset "$1").sha256")"
EOF
}

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by naspeed's release-binaries workflow. DO NOT EDIT.
class Naspeed < Formula
  desc "Transparent RUSTC_WRAPPER: crates cached once per volume, cloned copy-on-write"
  homepage "https://dacsang97.github.io/naspeed/"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
$(block aarch64-apple-darwin)
    end
    on_intel do
$(block x86_64-apple-darwin)
    end
  end

  on_linux do
    on_arm do
$(block aarch64-unknown-linux-musl)
    end
    on_intel do
$(block x86_64-unknown-linux-musl)
    end
  end

  def install
    bin.install "naspeed"
    bin.install_symlink "naspeed" => "ns"
  end

  def caveats
    <<~TEXT
      Point cargo at naspeed (copies the binary to ~/.cargo/bin):
        naspeed setup   # store in ~/.naspeed; --store <dir> for another volume
      Re-run \`naspeed setup\` after \`brew upgrade naspeed\` to refresh that copy.
    TEXT
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/naspeed --version")
  end
end
EOF
